# ------------------------------------------------------------------ formatting
def fx(x, dp):
    """定点格式化（与收件包显示的舍入约定一致）。"""
    return '%.*f' % (dp, float(x))


def lead(x, dp):
    """去掉个位零的写法：0.5717 -> .5717，1.004 -> 1.004。"""
    s = fx(x, dp)
    return s[1:] if s.startswith('0.') else s


def sgn(x, dp):
    """带符号定点：-0.0041 / +0.0000。"""
    return '%+.*f' % (dp, float(x))


def cm(x):
    """千分位整数计数。"""
    return '{:,}'.format(int(x))


def env_text(lines):
    return '\n'.join(lines)


