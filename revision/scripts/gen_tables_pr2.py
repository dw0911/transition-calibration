def build_all(A):
    out = {}
    for lab, fn in BUILDERS:
        txt = fn(A)
        assert '\t' not in txt, f'{lab}: 生成环境含制表符'
        nb = txt.count(r'\begin{tabular}') + txt.count(r'\begin{longtable}')
        ne = txt.count(r'\end{tabular}') + txt.count(r'\end{longtable}')
        assert nb == ne == 1, f'{lab}: 表格环境应恰好一个，实得 begin={nb} end={ne}'
        assert txt.startswith(r'\begin{') and (
            txt.endswith(r'\end{tabular}') or txt.endswith(r'\end{longtable}')), \
            f'{lab}: 环境首尾不是 \\begin/\\end'
        assert txt.count('{') == txt.count('}'), f'{lab}: 花括号不闭合'
        out[lab] = txt
    assert len(out) == 15
    return out


