# ------------------------------------------------------- 收件包环境的提取
ENV_RE = re.compile(r'\\begin\{(tabular|longtable)\}')


def received_envs():
    """{label: (src_key, 环境本体)}，按收件包源文件逐字节切出。"""
    out = {}
    for key in ('main', 'supp'):
        t = open(SRC[key], encoding='utf-8').read()
        for m in ENV_RE.finditer(t):
            env = m.group(1)
            close = '\\end{' + env + '}'
            e = t.index(close, m.start()) + len(close)
            txt = t[m.start():e]
            lab = re.search(r'\\label\{(tab:[a-z]+)\}', txt)
            if lab:
                lab = lab.group(1)
            else:
                prev = re.findall(r'\\label\{(tab:[a-z]+)\}', t[:m.start()])
                lab = prev[-1]
            assert lab not in out, f'{lab} 出现两次'
            out[lab] = (key, txt)
    assert len(out) == 15, f'收件包应有 15 个表格环境，实得 {len(out)}'
    return out


def only_last_col_diff(recv_env, gen_env):
    """登记偏离的唯一允许形状：逐行比较，差异只落在数据行的**最后一列**。

    返回 (是否合法, [(行号, 收件值, 生成值), ...])。
    """
    rl, gl = recv_env.split('\n'), gen_env.split('\n')
    if len(rl) != len(gl):
        return False, [('line-count', len(rl), len(gl))]
    diffs, cap_seen = [], 0
    for i, (a, b) in enumerate(zip(rl, gl)):
        if a == b:
            continue
        if '\\caption{' in a and '\\caption{' in b:
            # 只允许改图注文字：改动处不得含数字，且题注外的部分必须逐字相同
            k = next((j for j in range(min(len(a), len(b))) if a[j] != b[j]), None)
            if k is None or '\\caption{' not in a[:k]:
                return False, [(i, 'caption-prefix', '')]
            if re.search(r'\d', a[k:]) or re.search(r'\d', b[k:]):
                return False, [(i, 'caption-touches-a-number', '')]
            cap_seen += 1
            continue
        ca, cb = a.split(' & '), b.split(' & ')
        if len(ca) != len(cb) or ca[:-1] != cb[:-1] or not ca[-1].endswith('\\\\'):
            return False, [(i, a, b)]
        diffs.append((i, ca[-1], cb[-1]))
    return cap_seen <= 1, diffs


def working_copy(envs):
    """把收件包两份源里的表格环境替换成 \\input 行，其余字节不变。"""
    out = {}
    fixed = {}
    for key, path in SRC.items():
        t = open(path, encoding='utf-8').read()
        pieces, pos = [], 0
        for m in ENV_RE.finditer(t):
            env = m.group(1)
            close = '\\end{' + env + '}'
            e = t.index(close, m.start()) + len(close)
            lab = re.search(r'\\label\{(tab:[a-z]+)\}', t[m.start():e])
            if lab:
                lab = lab.group(1)
            else:
                lab = re.findall(r'\\label\{(tab:[a-z]+)\}', t[:m.start()])[-1]
            want = t[m.start():e]
            if lab in KNOWN_DEV:
                ok, _ = only_last_col_diff(want, envs[lab])
                assert ok, f'{lab}: 偏离超出登记的 flow-range 末列，拒绝替换'
            else:
                assert want == envs[lab], f'{lab} 与生成环境不一致，拒绝替换'
            pieces.append(t[pos:m.start()])
            pieces.append('\\input{' + input_path(lab) + '}')
            pos = e
        pieces.append(t[pos:])
        s = ''.join(pieces)
        for old, new in TEXT_FIXES:
            n = s.count(old)
            assert n in (0, 1), f'TEXT_FIXES 目标在 {key} 内出现 {n} 次'
            fixed[key] = fixed.get(key, 0) + n
            s = s.replace(old, new)
        out[key] = s
    assert sum(fixed.values()) == len(TEXT_FIXES), \
        f'登记的文字修正未全部命中: {fixed}'
    return out


# ------------------------------------------------------------------------- IO
def emit(envs, dest):
    os.makedirs(dest, exist_ok=True)
    for lab, txt in envs.items():
        fn = os.path.join(dest, written_name(lab))
        with open(fn, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(HDR + '\n' + txt + '\n')
    return sorted(envs)


def do_write(A, envs):
    emit(envs, GEN)
    wc = working_copy(envs)
    with open(os.path.join(OUT, 'main.tex'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(wc['main'])
    with open(os.path.join(OUT, 'supplement.tex'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(wc['supp'])
    for fn in ('references.bib', 'main.bbl'):
        shutil.copyfile(os.path.join(PKG, 'manuscript', fn), os.path.join(OUT, fn))
    print(f'已写出 {len(envs)} 个生成表 -> '
          + os.path.relpath(GEN, ROOT).replace(os.sep, '/'))
    print('已写出工作副本 -> paper/condensed/{main.tex, supplement.tex}，'
          '并复制 manuscript/{references.bib, main.bbl}')


def do_check(A, envs):
    rec = received_envs()
    tmp = tempfile.mkdtemp(prefix='pr2check_')
    try:
        emit(envs, tmp)
        rows, bad = [], 0
        for lab, _fn in BUILDERS:
            src, want = rec[lab]
            got = open(os.path.join(tmp, written_name(lab)), encoding='utf-8').read()
            status = 'PASS'
            if got != HDR + '\n' + want + '\n':
                legal, diffs = only_last_col_diff(want, envs[lab])
                if lab in KNOWN_DEV and legal:
                    status = f'DEVIATION-REGISTERED ({len(diffs)} cells)'
                    for i, old, new in diffs:
                        print(f'    {lab} 行{i}: 收件 {old}  ->  本地 {new}')
                else:
                    status = 'FAIL'
                    bad += 1
                    print(f'    {lab}: 与收件包不一致且不在登记偏离内')
            rows.append((lab, written_name(lab), os.path.basename(SRC[src]),
                         len(want.encode('utf-8')), status))
        print('  %-15s %-22s %-16s %8s  %s'
              % ('label', 'generated file', 'received source', 'bytes', 'status'))
        n_pass = sum(1 for r in rows if r[4] == 'PASS')
        for lab, fn, src, nb, status in rows:
            print('  %-15s %-22s %-16s %8d  %s' % (lab, fn, src, nb, status))
        print('--check: %d/%d 环境与收件包逐字节一致，其余为已登记偏离或 FAIL'
              % (n_pass, len(rows)))

        # 附加自检：工作副本与 generated/ 落盘内容也必须是本脚本的产物
        wc = working_copy(envs)
        extra = []
        for key, fn in (('main', 'main.tex'), ('supp', 'supplement.tex')):
            p = os.path.join(OUT, fn)
            have = open(p, encoding='utf-8').read() if os.path.exists(p) else None
            ok = have == wc[key]
            # 反向替换：把 \\input 行还原成收件包环境本体，必须与收件包源逐字节相同，
            # 这才能证明"除 15 处替换外没有其他任何字节变化"。
            back = have or ''
            for lab, (k, env) in rec.items():
                if k == key:
                    tok = '\\input{' + input_path(lab) + '}'
                    assert back.count(tok) == 1, f'{fn}: 缺少唯一的 {tok}'
                    back = back.replace(tok, env, 1)
            for old, new in TEXT_FIXES:          # 还原登记的文字修正
                back = back.replace(new, old)
            ident = back == open(SRC[key], encoding='utf-8').read()
            extra.append(ok and ident)
            print(f'  working copy {fn:<16} 与替换结果一致: '
                  + ('PASS' if ok else 'FAIL')
                  + ' | 还原 15 处 \\input 与登记文字修正后与收件包源逐字节相同: '
                  + ('PASS' if ident else 'FAIL'))
        disk = True
        for lab, _fn in BUILDERS:
            p = os.path.join(GEN, written_name(lab))
            txt = open(p, encoding='utf-8').read() if os.path.exists(p) else None
            disk = disk and txt == HDR + '\n' + envs[lab] + '\n'
        extra.append(disk)
        print('  paper/condensed/generated/ 落盘内容与本次重建一致: '
              + ('PASS' if disk else 'FAIL'))
        return 0 if bad == 0 and all(extra) else 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def do_out(A, envs, out_dir):
    """--out 模式：只把 15 张生成表写到 <out_dir>/generated/。

    供 PR3 合并稿基线 paper/integrated/ 复用同一条
    `results/**.json -> 生成器 -> generated/*.tex -> \\input` 通道；
    该基线的 main.tex/supplement.tex/references.bib/main.bbl 直接取自收件包
    （逐字节相同），故本模式不写工作副本、不复制 bib/bbl。
    """
    gen = os.path.join(out_dir, 'generated')
    emit(envs, gen)
    try:
        rel = os.path.relpath(gen, ROOT).replace(os.sep, '/')
    except ValueError:                              # 跨盘等情形，直接给绝对路径
        rel = gen
    print(f'已写出 {len(envs)} 个生成表 -> {rel}')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='只校验：重建到临时目录并与收件包环境逐字节比对，不写任何文件')
    ap.add_argument('--out', default=None, metavar='DIR',
                    help='只把 15 张生成表写到 DIR/generated/（默认：写 paper/condensed 完整工作副本）')
    args = ap.parse_args()
    A = Art()
    envs = build_all(A)
    if args.check:
        return do_check(A, envs)
    if args.out:
        do_out(A, envs, os.path.abspath(args.out))
        return 0
    do_write(A, envs)
    return 0


if __name__ == '__main__':
    sys.exit(main())
