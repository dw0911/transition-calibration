class Art(object):
    """只读加载 results/** 产物，并按"逐配置算完再对 3 种子平均"的口径提供聚合量。"""

    def __init__(self):
        self.v1 = {}
        for p in sorted(glob.glob(os.path.join(V1D, '*.json'))):
            n = os.path.basename(p)[:-5]
            if n != 'SUMMARY':
                self.v1[n] = json.load(open(p, encoding='utf-8'))
        self.sup = json.load(open(os.path.join(ROOT, 'results', 'phase3_PR1',
                                               'pr1_supplementary.json'),
                                  encoding='utf-8'))['configs']
        self.dsi = json.load(open(os.path.join(ROOT, 'results', 'phase3_PR1',
                                               'pr1_dataset_identity.json'),
                                  encoding='utf-8'))['datasets']
        self.c4 = json.load(open(os.path.join(ROOT, 'results', 'phase1_R1',
                                              'c4_decision_proxy_v2.json'),
                                 encoding='utf-8'))['configs']
        self.cop = json.load(open(os.path.join(ROOT, 'results', 'phase1_R1',
                                               'p08_copulacpts_v2.json'),
                                  encoding='utf-8'))['configs']
        afc = json.load(open(os.path.join(ROOT, 'results', 'phase2_E7',
                                          'author_finding_checks.json'), encoding='utf-8'))
        self.slopes = afc['A1_lambda_slopes']
        self.slope_sign = afc['A1_slope_sign_by_dataset']
        self.c3 = json.load(open(os.path.join(ROOT, 'results', 'phase2_E7',
                                              'cross_config_C3.json'),
                                 encoding='utf-8'))['L4_by_dataset']
        assert len(self.v1) == len(self.sup) == 12, '主实验应有 12 个配置'
        for ds in SUBS:
            for s in SEEDS:
                assert f'{ds}_s{s}' in self.v1 and f'{ds}_s{s}' in self.sup

    # ---- 原子访问
    def cfg(self, ds, seed):
        return f'{ds}_s{seed}'

    def m(self, ds, prog):
        """该子组 3 个配置的 metrics[prog] 节点列表。"""
        return [self.v1[self.cfg(ds, s)]['metrics'][prog] for s in SEEDS]

    def es(self, ds, seed, pair):
        return self.sup[self.cfg(ds, seed)]['effect_sizes'][pair]

    def seg(self, ds, tag):
        ident = self.sup[self.cfg(ds, 42)]['identity']
        return {x['tag']: x for x in ident['segments']}[tag]

    # ---- 聚合量（逐配置算完再平均）
    def path_cov(self, ds, prog):
        return float(np.mean([x['V1']['path_cov'] for x in self.m(ds, prog)]))

    def width_ratio(self, ds, prog):
        return float(np.mean([x['V1']['mean_width'] / y['V1']['mean_width']
                              for x, y in zip(self.m(ds, prog), self.m(ds, 'uncond'))]))

    def grp_cov(self, ds, prog, grp):
        return float(np.mean([x['V1']['group_path_cov'][grp] for x in self.m(ds, prog)]))

    def width_ratio_pair(self, ds, cand, ref):
        return float(np.mean([a['V1']['mean_width'] / b['V1']['mean_width']
                              for a, b in zip(self.m(ds, cand), self.m(ds, ref))]))

    def dcov(self, ds, cand, ref):
        return self.path_cov(ds, cand) - self.path_cov(ds, ref)

    def dg(self, ds, cand, ref, grp):
        return self.grp_cov(ds, cand, grp) - self.grp_cov(ds, ref, grp)

    def cell_cov(self, ds, grouping, cell, prog):
        return float(np.mean([self.sup[self.cfg(ds, s)]['prospective_paths'][grouping]
                              ['cells'][cell][prog]['path_cov'] for s in SEEDS]))

    def cell_width(self, ds, grouping, cell, prog):
        return float(np.mean([self.sup[self.cfg(ds, s)]['prospective_paths'][grouping]
                              ['cells'][cell][prog]['mean_width'] for s in SEEDS]))

    def cell_extremes(self, ds, grouping, prog):
        """gen_tables_pr1::_span 的同一口径：先按种子平均，再在六格上取极值。"""
        v = [self.cell_cov(ds, grouping, c, prog) for c in CELLS]
        return min(v), max(v)

    def cell_extremes_pooled(self, ds, grouping, prog):
        """跨"种子 × 六格"的 18 个逐配置格覆盖率上直接取 min/max。

        收件包 tab:cells 末列（complementary flow grouping 的 range）用的是这个口径，
        与主稿 tab:prospective 的"先按种子平均、再在六格上取极值"不同：
        20 行里两者在 6 行上末位不同，逐字节比对选出的正是本口径。
        """
        v = [self.sup[self.cfg(ds, s)]['prospective_paths'][grouping]
             ['cells'][c][prog]['path_cov'] for s in SEEDS for c in CELLS]
        return min(v), max(v)

    def cell_count(self, ds, cell, prog='uncond'):
        return int(self.sup[self.cfg(ds, 42)]['prospective_paths']['mag']
                   ['cells'][cell][prog]['n_v1_paths'])

    def c4mean(self, ds, thr, meth, field):
        return float(np.mean([self.c4[self.cfg(ds, s)]['thresholds'][thr]
                              ['methods'][meth][field] for s in SEEDS]))


